"""第 2 章的交互式课程。"""

from __future__ import annotations

from minimem.learn.models import Apply, Card, Cliff, Explain, Lesson, Motto, Predict, Recall, Run

LESSON = Lesson(
    chapter=2,
    title="上下文与长上下文记忆",
    minutes=30,
    difficulty=1,
    prerequisites=[1],
    steps=[
        Motto("上下文总会满。问题不是会不会丢，而是丢什么。"),
        Predict(
            question=(
                "一段 40 轮的对话，用户在**第 3 轮**说了「我对花生过敏」，"
                "之后全是日常闲聊。窗口预算只装得下十几轮。"
                "用最常见的「丢最旧的」策略，最后问「我对什么过敏」，能答对吗？"
            ),
            options={
                "A": "能 —— 过敏这么重要的信息系统会保留",
                "B": "不能 —— 它恰好是最先被丢掉的三条之一",
            },
            answer="B",
            reveal=(
                "「丢最旧的」丢掉的恰好是最该留的。这不是巧合："
                "**用户倾向于在对话开头交代背景**——姓名、职业、禁忌、目标——"
                "然后在几十轮之后期待你还记得。"
            ),
            trap=(
                "选 A 的人默认系统会「识别重要性」。但滑动窗口不看重要性，只看年龄。"
                "而重要性和年龄在对话里往往是**负相关**的。"
            ),
        ),
        Run(
            script="docs/chapter2/code/01_what_gets_dropped.py",
            why="对比三种淘汰策略，并看看「丢最旧」到底丢掉了哪三条。",
            look_for="上下文 token 那一列——三种策略成本几乎相同，效果差别巨大。",
            minutes=1,
        ),
        Recall(
            question="sink 策略（保留开头几条）能救回哪类信息？又救不了哪类？",
            answer=(
                "能救「开场交代的背景」——姓名、职业、长期禁忌、目标。"
                "救不了「中途才出现的关键信息」，比如第 20 轮才说的「我换工作了」。"
                "后者需要 pinned（钉住）或检索，而「谁来判断哪条值得钉」本身"
                "就是一次额外的判断成本。"
            ),
        ),
        Predict(
            question=(
                "在**相同的 token 预算**下，两种做法：（1）保留最近的原始对话；"
                "（2）把 20 轮对话压成结构化事实。7 个关键信息点，各能覆盖几个？"
            ),
            options={
                "A": "截断 1/7，摘要 7/7",
                "B": "截断 4/7，摘要 6/7",
                "C": "两者差不多 —— 压缩会丢信息，抵消了优势",
            },
            answer="A",
            reveal=(
                "截断只覆盖 1/7，摘要覆盖 7/7。"
                "截断保留的是「最近说的」，摘要保留的是「重要的」，"
                "而这两者在对话里往往不重合。"
            ),
            trap=(
                "选 C 的直觉是「压缩必然丢信息」。压缩确实丢信息，"
                "但它丢的是**寒暄和冗余**；截断丢的是**事实本身**。"
                "关键是看丢掉的那部分值不值钱。"
            ),
        ),
        Run(
            script="docs/chapter2/code/02_compression.py",
            why="看压缩率与信息覆盖，更重要的是看**摘要丢掉了什么**。",
            look_for="「我对花生过敏，点餐要注意」被压成「过敏原：花生」之后，少了什么。",
            minutes=1,
        ),
        Recall(
            question="摘要式记忆最隐蔽的失真是什么？",
            answer=(
                "**不确定性被抹掉**。原文「这个项目做了快一年了」是模糊表述，"
                "压成「项目周期：一年」就变成了确定断言。"
                "压缩会系统性地把「大概、可能、我记得」变成事实。"
                "其次是**行动指引丢失**：「点餐要注意」这层意思不在「属性=值」的模式里。"
            ),
        ),
        Recall(
            question="StreamingLLM 的 attention sink 解决了什么问题？没解决什么？",
            answer=(
                "它解决的是 KV cache 层面的**数值稳定性**：保留最初几个 token，"
                "流式解码就不会崩。它**不扩展模型的有效上下文长度**。"
                "本章借用的只是「保留开头」这个形状，"
                "而我们处理的是应用层「历史太长塞不下」的信息取舍——两者不是同一个问题。"
                "把它们混为一谈是这个领域常见的以讹传讹。"
            ),
        ),
        Explain(
            task="向同事解释：为什么「上下文窗口够大就不需要记忆系统了」这句话是错的。",
            checklist=[
                "说出成本的增长阶（O(N²)），而不只是「贵」",
                "提到窗口大小解决不了跨会话、多用户隔离、可删除、可审计",
                "引用长上下文的质量衰减（塞得下 ≠ 用得好）",
                "承认它在短对话里确实是对的——不要走向另一个极端",
            ],
        ),
        Apply(
            level="🟢",
            task="把实验一的 BUDGET 从 260 调到 500，看三种策略的差距怎么变。",
            starting_point="docs/chapter2/code/01_what_gets_dropped.py 顶部的 BUDGET",
            success_looks_like="预算够大时三种策略趋同——**窗口策略只在预算紧张时才重要**",
        ),
        Apply(
            level="🟡",
            task=(
                "给 WindowMemory 加一种 'summary' 策略：被挤出窗口的内容不是丢弃，"
                "而是压成一条摘要留在窗口里。用实验一验证它能否答对过敏题。"
            ),
            starting_point="minimem/window.py 的 visible()，可复用实验二的 rule_summarize",
            success_looks_like="窗口内条数增加一条「摘要」，且过敏题答对",
            verify="python -m pytest tests/test_window.py -q",
        ),
        Apply(
            level="🔴",
            task=(
                "实现「摘要退化」的测量：把一段对话反复摘要 5 次（摘要的摘要的摘要……），"
                "每轮测一次关键信息覆盖率，画出退化曲线。"
            ),
            starting_point="docs/chapter2/code/02_compression.py 的 rule_summarize",
            success_looks_like="一条随迭代次数下降的曲线——这正是第 7 章分层调度要面对的问题",
        ),
        Cliff(
            text=(
                "窗口方案用「彻底遗忘」换来了恒定成本。但被丢掉的东西**再也找不回来**了。"
                "有没有办法既不全带，又不真丢？"
            ),
            next_chapter="第 3 章：不丢弃，但也不全带——用检索决定每一轮带哪几条。",
        ),
    ],
    cards=[
        Card(
            front="为什么「丢最旧的」是最糟糕的默认淘汰策略？",
            back=(
                "因为用户倾向于在对话开头交代背景（姓名、职业、禁忌、目标），"
                "而这些恰好是最先被丢掉的。重要性和年龄在对话里往往负相关。"
                "改成保留开头几条（sink），成本几乎不变，效果差别巨大。"
            ),
            chapter=2,
        ),
        Card(
            front="相同 token 预算下，截断和摘要哪个信息密度高？为什么？",
            back=(
                "摘要高得多（实测 7/7 对 1/7）。截断保留「最近说的」，"
                "摘要保留「重要的」，而两者在对话里往往不重合。"
                "但摘要的代价是每次要一次 LLM 调用，且会丢失行动指引与不确定性。"
            ),
            chapter=2,
        ),
        Card(
            front="StreamingLLM 扩展了模型的有效上下文长度吗？",
            back=(
                "没有。它解决的是 KV cache 的数值稳定性——保留最初几个 token"
                "（attention sink）让流式解码不崩。把它说成「让模型能记更多」是误传。"
            ),
            chapter=2,
        ),
        Card(
            front="压缩式记忆最隐蔽的失真是什么？",
            back=(
                "不确定性被抹掉。「这个项目做了快一年了」→「项目周期：一年」，"
                "模糊表述变成确定断言。其次是行动指引丢失："
                "「我对花生过敏，点餐要注意」→「过敏原：花生」，后半句的约束没了。"
            ),
            chapter=2,
        ),
    ],
)
